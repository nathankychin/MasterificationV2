def _initialize_postgres():
    with connect_db() as db:
        db.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)")
        applied = {row["version"] for row in db.execute("SELECT version FROM schema_migrations").fetchall()}
        for version, statements in sorted(POSTGRES_MIGRATIONS.items()):
            if version in applied:
                continue
            for statement in statements:
                db.execute(statement)
            db.execute("INSERT INTO schema_migrations(version) VALUES(?)", (version,))


def initialize_db():
    if database_backend() == "postgresql":
        _initialize_postgres()
    else:
        _initialize_sqlite()


def record_ai_diagnostic(diagnostic):
    allowed_tasks = {"scenario", "feedback", "connectivity_test"}
    task = diagnostic.get("task")
    if task not in allowed_tasks:
        raise ValueError("Unsupported AI diagnostic task.")
    safe_values = (
        now_timestamp(),
        task,
        bool(diagnostic["success"]),
        diagnostic.get("error_category"),
        diagnostic.get("http_status"),
        diagnostic["model"],
        max(0, int(diagnostic.get("latency_ms", 0))),
        bool(diagnostic.get("fallback_used", False)),
        diagnostic.get("safe_message"),
    )
    with connect_db() as db:
        db.execute(
            "INSERT INTO ai_diagnostics(created_at,task,success,error_category,http_status,model,latency_ms,fallback_used,safe_message) VALUES(?,?,?,?,?,?,?,?,?)",
            safe_values,
        )


def now_timestamp():
    return datetime.now(timezone.utc).replace(microsecond=0)


def is_integrity_error(error):
    if isinstance(error, sqlite3.IntegrityError):
        return True
    try:
        import psycopg
    except ImportError:
        return False
    return isinstance(error, psycopg.IntegrityError)