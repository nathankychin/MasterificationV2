class DatabaseConnection:
    def __init__(self, connection, postgres):
        self._connection = connection
        self.is_postgres = postgres

    def _sql(self, statement):
        return statement.replace("?", "%s") if self.is_postgres else statement

    def _parameters(self, parameters):
        if self.is_postgres:
            return parameters
        return tuple(value.isoformat(timespec="seconds") if isinstance(value, datetime) else value for value in parameters)

    def execute(self, statement, parameters=()):
        return self._connection.execute(self._sql(statement), self._parameters(parameters))

    def executemany(self, statement, parameter_rows):
        cursor = self._connection.cursor()
        cursor.executemany(self._sql(statement), (self._parameters(row) for row in parameter_rows))
        return cursor

    def executescript(self, script):
        if self.is_postgres:
            raise RuntimeError("PostgreSQL migrations execute versioned statements individually.")
        return self._connection.executescript(script)

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()


def database_backend():
    return "postgresql" if os.environ.get("DATABASE_URL", "").strip() else "sqlite"


def database_configuration():
    if database_backend() == "postgresql":
        return {"backend": "postgresql", "configured": True, "path_type": "database_url_env"}
    configured_path = bool(os.environ.get("SKILLTRACKER_DB", "").strip())
    return {
        "backend": "sqlite",
        "configured": configured_path,
        "path_type": "configured_env" if configured_path else "default",
    }


def _connect():
    database_url = os.environ.get("DATABASE_URL", "").strip()
    if database_url:
        import psycopg
        from psycopg.rows import dict_row

        connection = psycopg.connect(database_url, row_factory=dict_row, connect_timeout=10)
        return DatabaseConnection(connection, postgres=True)
    if os.environ.get("RENDER", "").lower() == "true" or os.environ.get("RENDER_SERVICE_ID"):
        raise RuntimeError("DATABASE_URL must be configured for Render PostgreSQL deployment.")
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(DB_PATH, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return DatabaseConnection(connection, postgres=False)


@contextmanager
def connect_db():
    connection = _connect()
    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


